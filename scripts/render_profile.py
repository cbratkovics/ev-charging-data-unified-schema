#!/usr/bin/env python
"""Render docs/PROFILE.md and the inventory block of docs/DATA_SOURCES.md from the newest
profile artifact. Every number in those documents comes from the artifact and carries its
run id; nothing is typed by hand.

    python scripts/render_profile.py [--artifact artifacts/profile/<run_id>.json] [--check]
"""

from __future__ import annotations

