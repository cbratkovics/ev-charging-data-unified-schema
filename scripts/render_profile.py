INVENTORY_START = "<!-- generated:inventory start -->"
INVENTORY_END = "<!-- generated:inventory end -->"
SOURCE_TITLES = {
    "cary": "Cary, NC",
    "boulder": "Boulder, CO",
    "dft_2017": "UK DfT, Electric Chargepoint Analysis 2017",
}


def latest_artifact(out_dir: Path) -> Path:
    latest = json.loads((out_dir / "latest.json").read_text())
    return out_dir / latest["path"]


def pct(num: int | None, den: int | None) -> str:
    if num is None or not den:
        return "n/a"
    return f"{100 * num / den:.2f}%"


def fmt(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return str(v)
    if isinstance(v, float):
        return f"{v:,.3f}".rstrip("0").rstrip(".")
    if isinstance(v, int):
        return f"{v:,}"
    return str(v)


def table(headers: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def kv(d: dict[str, Any], sep: str = ", ") -> str:
    return sep.join(f"{k} {fmt(v)}" for k, v in d.items())


def base(path: str) -> str:
    return "`" + path.split("/")[-1] + "`"


# --- inventory ---------------------------------------------------------------------------------


def inventory_rows(art: dict[str, Any]) -> list[list[Any]]:
    rows = []
    for name, src in art["sources"].items():
        title = SOURCE_TITLES.get(name, name)
        if not src.get("available"):
            rows.append([title, "(none downloaded)", "n/a", "n/a", "n/a", "n/a"])
            continue
        for f in src["files"]:
            dl = f.get("download") or {}
            rows.append(
                [
                    title,
                    base(f["path"]),
                    dl.get("retrieved_at", "n/a"),
                    f["bytes"],
                    f["rows"],
                    "`" + f["sha256"][:16] + "…`",
                ]
            )
    return rows


def render_inventory(art: dict[str, Any]) -> str:
    body = table(
        ["Source", "File", "Retrieved (UTC)", "Bytes", "Data rows", "SHA-256 (prefix)"],
        inventory_rows(art),
    )
    return (
        f"{INVENTORY_START}\n"
        f"_Generated by `scripts/render_profile.py` from `artifacts/profile/{art['run_id']}.json` "
        f"(code commit `{art['code_commit'][:12]}`); full hashes are in the artifact._\n\n"
        f"{body}\n{INVENTORY_END}"
    )


# --- per-source sections -----------------------------------------------------------------------


def column_table(f: dict[str, Any]) -> str:
    rows = []
    for c in f["column_profiles"]:
        extra = ""
        if c["inferred_type"] in ("integer", "decimal"):
            extra = f"min {fmt(c['min'])}, max {fmt(c['max'])}, zeros {fmt(c['zero_count'])}"
        elif c["inferred_type"] in ("datetime", "date"):
            extra = f"{c['min']} → {c['max']}"
            ev = c.get("day_first_evidence")
            if ev:
                extra += (
                    f"; day-first evidence: {ev['verdict']} "
                    f"({fmt(ev['first_field_gt_12'])} values with first field > 12)"
                )
        elif c["inferred_type"] == "duration_hms":
            extra = (
                f"{fmt(c['min_minutes'])} → {fmt(c['max_minutes'])} min, zeros {fmt(c['zero_count'])}, "
                f"over 24 h {fmt(c['over_24h_count'])}"
            )
        typ = c["inferred_type"] + (f" ({c['pattern']})" if c.get("pattern") else "")
        rows.append(
            [f"`{c['name']}`", typ, pct(c["null_or_blank"], c["rows"]), c["distinct"], extra]
        )
    return table(["Column", "Inferred type", "Null / blank", "Distinct", "Range and notes"], rows)


def hist_line(h: dict[str, int], width: int = 24) -> str:
    items = sorted(h.items(), key=lambda kv_: int(kv_[0]))
    if not items:
        return ""
    mx = max(v for _, v in items) or 1
    return "\n".join(
        f"    {int(k):>2}h {'█' * max(1, round(width * v / mx)):<{width}} {v:,}" for k, v in items
    )


def files_section(src: dict[str, Any], a: dict[str, Any]) -> list[str]:
    out = ["### Files\n"]
    out.append(
        table(
            ["File", "Family", "Bytes", "Data rows", "Exact duplicate rows", "Columns"],
            [
                [
                    base(f["path"]),
                    f.get("family") or "-",
                    f["bytes"],
                    f["rows"],
                    f["exact_duplicate_rows"],
                    len(f["columns"]),
                ]
                for f in src["files"]
            ],
        )
    )
    if any(f.get("na_token_counts") for f in src["files"]):
        out.append(
            "\nLiteral `NA` tokens (treated as null in every count below): "
            + "; ".join(
                f"{base(f['path'])}: {kv(f['na_token_counts'])}"
                for f in src["files"]
                if f.get("na_token_counts")
            )
            + "."
        )
    if len(src["files"]) > 1:
        heads = {base(f["path"]): f["columns"] for f in src["files"]}
        first = next(iter(heads.values()))
        diffs = []
        for n, cols in heads.items():
            if cols == first:
                continue
            added = [c for c in cols if c not in first]
            lacking = [c for c in first if c not in cols]
            parts = []
            if added:
                parts.append("adds " + ", ".join(f"`{c}`" for c in added))
            if lacking:
                parts.append("lacks " + ", ".join(f"`{c}`" for c in lacking))
            if not parts:
                parts.append("same columns in a different order")
            diffs.append(f"{n}: " + "; ".join(parts))
        out.append(
            "\nHeader differences versus the first file: "
            + ("; ".join(diffs) if diffs else "none")
            + "."
        )
    if a.get("fully_blank_rows"):
        out.append(
            f"\nFully blank rows across files: {fmt(a['fully_blank_rows'])} (excluded from every count below)."
        )
    cov = a["coverage"]
    out.append(
        f"\nSessions start {cov['start_min']} → {cov['start_max']} (as published, before timezone handling). By year: "
        + kv(cov["sessions_by_year"], ", ").replace(" ", ": ", 0)
        + "."
    )
    if len(cov["files_by_start_range"]) > 1:
        out.append(
            "\n"
            + table(
                ["File", "Rows", "First start", "Last start"],
                [
                    [f"`{f}`", v["rows"], v["start_min"], v["start_max"]]
                    for f, v in cov["files_by_start_range"].items()
                ],
            )
        )
    return out


