def timezone_section(a: dict[str, Any]) -> list[str]:
    tz = a["timezone"]
    out = [
        f"\n### Timezone evidence\n\nAssumed station zone `{tz['assumed_zone']}`; published format `{tz['start_format']}`."
    ]
    if "seasonal_shift" in tz:
        s = tz["seasonal_shift"]
        out.append(
            f"\nSeasonal shift of the raw-hour profile (amendment c): circular mean raw start hour in summer (DST, "
            f"{fmt(s['summer_dst']['rows'])} rows) {fmt(s['summer_dst']['circular_mean_raw_hour'])}, in winter "
            f"({fmt(s['winter_std']['rows'])} rows) {fmt(s['winter_std']['circular_mean_raw_hour'])}; summer minus winter "
            f"{fmt(s['summer_minus_winter_mean_raw_hour'])} hours. Reading: {s['reading']}."
        )
    if "tz_label_values" in tz:
        months = sorted(tz["tz_label_by_start_month"].items(), key=lambda kv_: int(kv_[0]))
        labels = sorted({c for _, r in months for c in r})
        out.append(
            f"\nTimezone label values: {kv(tz['tz_label_values'])}. Label by start month (a label that says MDT in "
            "January is not a per-row offset):\n\n"
            + table(["Month", *labels], [[m, *[r.get(c, 0) for c in labels]] for m, r in months])
        )
    if "dst_transition_gaps" in tz:
        out.append(
            f"\n{tz['dst_note']}:\n\n"
            + table(
                [
                    "Transition date",
                    "Sessions spanning 01:00-02:00",
                    "(end - start) - duration, minutes: count",
                ],
                [
                    [
                        d,
                        v["sessions_spanning_window"],
                        ", ".join(f"{g}: {c}" for g, c in v["gap_minutes_counts"].items()) or "-",
                    ]
                    for d, v in tz["dst_transition_gaps"].items()
                ],
            )
        )
    out.append(
        "\nStart hour histogram as published:\n\n```\n"
        + hist_line(tz["start_hour_histogram_as_published"])
        + "\n```"
    )
    if "start_hour_histogram_if_utc_converted_to_local" in tz:
        out.append(
            f"\n{tz['note']}. Converted to `{tz['assumed_zone']}`:\n\n```\n"
            + hist_line(tz["start_hour_histogram_if_utc_converted_to_local"])
            + "\n```"
        )
    return out


def capacity_section(a: dict[str, Any]) -> list[str]:
    out: list[str] = []
    if "observed_concurrency" in a:
        oc = a["observed_concurrency"]
        out.append(
            f"\n### Observed concurrency (capacity evidence)\n\nAfter natural-key deduplication, on {fmt(oc['sessions_used'])} "
            f"sessions of at least {oc['min_session_minutes']} minutes, the maximum number of simultaneously open sessions "
            "per key (a lower bound on ports in service):"
        )
        for label in ("by_station_key", "by_site_key"):
            if label in oc:
                c = oc[label]
                out.append(
                    f"\n- by `{c['key']}` ({fmt(c['keys'])} keys): "
                    + ", ".join(f"max {k} at {fmt(v)} keys" for k, v in c["distribution"].items())
                    + ". Highest: "
                    + ", ".join(f"{k} = {v}" for k, v in c["top"].items())
                    + "."
                )
        if "days_at_level" in oc:
            d = oc["days_at_level"]
            levels = sorted({int(k) for h in d["robust_max_histogram_by_n"].values() for k in h})
            out.append(
                f"\nRobust max by `{d['key']}` (amendment f): {d['note']}. Histogram of the robust max over keys, by N:\n\n"
                + table(
                    ["N days", *[f"max {k}" for k in levels]],
                    [
                        [n, *[h.get(str(k), 0) for k in levels]]
                        for n, h in sorted(
                            d["robust_max_histogram_by_n"].items(), key=lambda kv_: int(kv_[0])
                        )
                    ],
                )
                + f"\n\nKeys whose plain max exceeds the robust max at N = 5: {fmt(d['keys_where_plain_max_exceeds_robust_max_n5'])}. "
                "Days-at-level quantiles (p10 / p50 / p90) per level: "
                + "; ".join(
                    f"level {lvl}: " + " / ".join(fmt(v) for v in q.values())
                    for lvl, q in d["days_at_level_quantiles"].items()
                )
                + "."
            )
        if "inter_session_gaps" in oc:
            g = oc["inter_session_gaps"]
            out.append(
                f"\nInter-session gaps by `{g['key']}` (amendment g), end of one session to start of the next, on "
                f"{fmt(g['gaps'])} gaps: quantiles (days) "
                + ", ".join(f"p{float(k) * 100:g} {fmt(v)}" for k, v in g["quantiles_days"].items())
                + ". Gaps longer than: "
                + ", ".join(f"{dd} d: {fmt(v)}" for dd, v in g["gaps_over_days"].items())
                + f". Keys with at least one gap over 30 days: {fmt(g['keys_with_a_gap_over_30d'])}."
            )
    if "charge_points_per_site" in a:
        c = a["charge_points_per_site"]
        out.append(
            f"\nStation ids per `{c.get('grouped_by', 'site')}` ({fmt(c['sites'])} groups): "
            + ", ".join(
                f"{k} id(s) at {fmt(v)} groups"
                for k, v in sorted(c["distribution"].items(), key=lambda kv_: int(kv_[0]))
            )
            + ". Largest: "
            + ", ".join(f"{k} = {v}" for k, v in c["top"].items())
            + "."
        )
    return out


def render_source(name: str, src: dict[str, Any]) -> str:
    title = SOURCE_TITLES.get(name, name)
    if not src.get("available"):
        return f"## {title}\n\n**Not profiled.** {src.get('reason', 'no file available')}\n"
    a = src["answers"]
    out = [f"## {title}\n"]
    out += files_section(src, a)
    out.append("\n### Columns (first file)\n")
    out.append(column_table(src["files"][0]))
    out += questions_section(a)
    out += timezone_section(a)
    out += capacity_section(a)
    pdata = a["personal_data"]
    out.append(
        "\n### Personal data\n\n"
        + (
            "User-level columns: " + ", ".join(f"`{c}`" for c in pdata["user_level_columns"])
            if pdata["user_level_columns"]
            else "No user-level columns. Address, city, state, postal-code and organisation-name columns describe the station or its funder."
        )
        + " (docs/adr/0003-personal-data.md).\n"
    )
    return "\n".join(out)


def render_profile(art: dict[str, Any]) -> str:
    head = [
        "# Source profiles\n",
        f"_Generated by `scripts/render_profile.py` from `artifacts/profile/{art['run_id']}.json` (code commit "
        f"`{art['code_commit'][:12]}`, generated {art['generated_at_utc']}). Every number on this page is read from that "
        "artifact; the artifact records each input file's sha256, byte size and row count and the definitions of every "
        "measure. Do not edit by hand._\n",
        "Raw files are git-ignored (docs/adr/0002-source-redistribution.md). Shares are of non-blank rows across all of a "
        "source's files before any deduplication unless stated.\n",
        "## Definitions\n",
        "\n".join(f"- **{k}**: {v}" for k, v in art["definitions"].items()) + "\n",
    ]
    body = [render_source(n, art["sources"][n]) for n in art["sources"]]
    return "\n".join(head + body)


def splice_inventory(doc: str, block: str) -> str:
    pat = re.compile(re.escape(INVENTORY_START) + r".*?" + re.escape(INVENTORY_END), re.S)
    if not pat.search(doc):
        raise SystemExit("docs/DATA_SOURCES.md has no generated:inventory markers")
    return pat.sub(lambda _m: block, doc)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--artifact", type=Path, default=None)
    p.add_argument(
        "--check",
        action="store_true",
        help="fail if the rendered docs differ from the committed ones",
    )
    a = p.parse_args(argv)
    path = a.artifact or latest_artifact(ARTIFACTS_DIR / "profile")
    art = json.loads(path.read_text())
    profile_md = render_profile(art)
    ds_path = REPO_ROOT / "docs" / "DATA_SOURCES.md"
    ds_md = splice_inventory(ds_path.read_text(encoding="utf-8"), render_inventory(art))
    targets = {REPO_ROOT / "docs" / "PROFILE.md": profile_md, ds_path: ds_md}
    if a.check:
        stale = [
            str(t.relative_to(REPO_ROOT))
            for t, text in targets.items()
            if not t.exists() or t.read_text(encoding="utf-8") != text
        ]
        if stale:
            print(
                "stale rendered docs: "
                + ", ".join(stale)
                + "; run python scripts/render_profile.py"
            )
            return 1
        print("ok: rendered docs match the profile artifact")
        return 0
    for t, text in targets.items():
        t.write_text(text, encoding="utf-8")
        print(f"wrote {t.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
